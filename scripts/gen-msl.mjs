#!/usr/bin/env node
// Writes the Metal shaders of the Swift wet-media engine from the WGSL kernels of the TS core, so
// the GPU code has one source. naga (https://github.com/gfx-rs/wgpu/tree/trunk/naga) translates
// WGSL to MSL; this script then numbers the buffer arguments by their WGSL `@binding` (naga's CLI
// leaves them as `[[user(fake0)]]`) and embeds the source in Swift, which compiles it at run time
// (as WebGPU compiles WGSL). Run after `pnpm build` whenever a kernel in
// `packages/core/src/paint/wet/gpu-kernels.ts` changes, then commit what changed.
//
// Needs naga-cli (`cargo install naga-cli`); set NAGA to its path if it is not on PATH or in
// ~/.cargo/bin. CI has no naga: `tests/swift-shaders.test.ts` checks the WGSL hash recorded in the
// output instead, so a kernel change without a rerun fails there.
//
// Output: packages/swift/Sources/PixeratePaint/GeneratedShaders/WetShaders.swift
//
// Usage: node scripts/gen-msl.mjs [--check]

import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const out = path.join(root, "packages/swift/Sources/PixeratePaint/GeneratedShaders/WetShaders.swift");

const dist = path.join(root, "packages/core/dist/paint/index.js");
if (!fs.existsSync(dist)) {
  console.error("No packages/core/dist/paint/index.js: build the core first (pnpm --filter @pixerate/editor build).");
  process.exit(1);
}
const { WGSL_SHADE } = await import(pathToFileURL(dist).href);

function findNaga() {
  const candidates = [process.env.NAGA, "naga", path.join(os.homedir(), ".cargo/bin/naga")].filter(Boolean);
  for (const bin of candidates) {
    try {
      const version = execFileSync(bin, ["--version"], { encoding: "utf8" }).trim();
      return { bin, version };
    } catch {
      // try the next one
    }
  }
  console.error("naga was not found: install it with `cargo install naga-cli`, or set NAGA to its path.");
  process.exit(1);
}
const naga = findNaga();

/** WGSL → MSL with every buffer argument at its WGSL binding (the hidden size buffer after them). */
function translate(name, wgsl) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "pixerate-msl-"));
  try {
    const src = path.join(tmp, `${name}.wgsl`);
    const dst = path.join(tmp, `${name}.metal`);
    fs.writeFileSync(src, wgsl);
    execFileSync(naga.bin, ["--metal-version", "2.1", src, dst], { stdio: "pipe" });
    let msl = fs.readFileSync(dst, "utf8");
    const bindings = new Map();
    for (const m of wgsl.matchAll(/@binding\((\d+)\)\s*var(?:<[^>]*>)?\s+(\w+)\s*:/g)) bindings.set(m[2], Number(m[1]));
    const sizes = Math.max(...bindings.values()) + 1;
    msl = msl.replace(/(\w+)\s*\[\[user\(fake0\)\]\]/g, (all, arg) => {
      if (arg === "_buffer_sizes") return `${arg} [[buffer(${sizes})]]`;
      if (!bindings.has(arg)) throw new Error(`${name}: naga made an argument "${arg}" that no WGSL binding names.`);
      return `${arg} [[buffer(${bindings.get(arg)})]]`;
    });
    if (msl.includes("fake0")) throw new Error(`${name}: an argument kept its placeholder binding.`);
    return { msl, sizes };
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

const sha = (text) => crypto.createHash("sha256").update(text).digest("hex");
const shade = translate("wet_shade", WGSL_SHADE);
if (shade.msl.includes('"""#')) throw new Error("The MSL contains the Swift raw-string terminator.");

const text = `// Generated by scripts/gen-msl.mjs from WGSL_SHADE (packages/core/src/paint/wet/gpu-kernels.ts) with naga ${naga.version.replace(/^naga\s*/, "")}. Do not edit.

/// SHA-256 of the WGSL this was made from (\`tests/swift-shaders.test.ts\` compares it with the core's).
let WET_SHADE_WGSL_SHA256 = "${sha(WGSL_SHADE)}"

/// The kernel's entry point in \`WET_SHADE_MSL\`.
let WET_SHADE_ENTRY = "main_"

/// Buffer index of naga's hidden buffer-sizes argument (after the WGSL bindings).
let WET_SHADE_SIZES_INDEX = ${shade.sizes}

/// The display shading of wet tiles (\`WGSL_SHADE\` in Metal Shading Language).
let WET_SHADE_MSL = #"""
${shade.msl.trimEnd()}
"""#
`;

const was = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
if (was === text) {
  console.log("gen-msl: up to date");
} else if (check) {
  console.error(`${path.relative(root, out)} is out of date: run node scripts/gen-msl.mjs and commit it.`);
  process.exit(1);
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  console.log(`gen-msl: wrote ${path.relative(root, out)}`);
}
