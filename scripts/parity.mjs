#!/usr/bin/env node
// Writes the feature matrix from parity/features.json: the "Feature parity" section of the root
// README and the demo's parity tab data (apps/demo/src/parityFeatures.generated.ts). It also checks
// that every component, hook, factory and type a cell names in backticks exists in that package
// (core, React, Svelte or Swift), so a renamed or removed API fails the check instead of leaving
// the matrix wrong. A core test (`tests/parity-manifest.test.ts`) runs `--check`.
//
// Usage: node scripts/parity.mjs [--check]   (--check writes nothing and exits 1 on any problem)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "parity/features.json"), "utf8"));
const COLUMNS = [
  ["core", "Core"],
  ["react", "React"],
  ["svelte", "Svelte"],
  ["swift", "Swift"],
];
const problems = [];

// MARK: README

const README_INTRO =
  'Every feature is available from core and from both framework packages, except where a footnote says otherwise. "Via core" means the framework package uses the core API directly, with no extra wrapper. The Swift column tracks the native editors (#533): what is ported, and the issue for what is planned. This section is generated from [`parity/features.json`](./parity/features.json) by `node scripts/parity.mjs`; edit that file, not this section. Expand an area for the details.';

function readmeSection() {
  let text = "## Feature parity\n\n" + README_INTRO + "\n";
  for (const area of manifest.areas) {
    text += `\n<details>\n<summary><strong>${area.title}</strong> (${area.features.length})</summary>\n\n`;
    text += `| Feature | ${COLUMNS.map(([, label]) => label).join(" | ")} |\n| :--- | ${COLUMNS.map(() => ":---:").join(" | ")} |\n`;
    for (const f of area.features) text += `| ${f.feature} | ${COLUMNS.map(([key]) => f[key]).join(" | ")} |\n`;
    text += "\n</details>\n";
  }
  if (manifest.notes.length) text += "\n" + manifest.notes.join("\n\n") + "\n";
  return text + "\n";
}

const readmePath = path.join(root, "README.md");
const readme = fs.readFileSync(readmePath, "utf8");
const start = readme.indexOf("## Feature parity\n");
const end = readme.indexOf("\n## ", start + 1);
if (start < 0 || end < 0) throw new Error('README.md needs a "## Feature parity" section followed by another "## " heading.');
const nextReadme = readme.slice(0, start) + readmeSection() + readme.slice(end + 1);

// MARK: demo

const demoPath = path.join(root, "apps/demo/src/parityFeatures.generated.ts");
const demo =
  "// Generated by scripts/parity.mjs from parity/features.json. Do not edit.\n\n" +
  "export interface ParityFeature {\n  feature: string;\n  core: string;\n  react: string;\n  svelte: string;\n  swift: string;\n}\n\n" +
  "export interface ParityArea {\n  title: string;\n  features: ParityFeature[];\n}\n\n" +
  `export const PARITY_AREAS: ParityArea[] = ${JSON.stringify(
    manifest.areas.map((a) => ({ title: a.title, features: a.features.map((f) => ({ feature: f.feature, core: f.core, react: f.react, svelte: f.svelte, swift: f.swift })) })),
    null,
    2,
  )};\n\nexport const PARITY_NOTES: string[] = ${JSON.stringify(manifest.notes, null, 2)};\n`;

// MARK: symbols

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** Names a TypeScript package exports from any of its source files (and its Svelte components). */
function tsNames(pkg) {
  const names = new Set();
  for (const f of walk(path.join(root, "packages", pkg, "src"))) {
    if (f.endsWith(".svelte")) {
      names.add(path.basename(f, ".svelte"));
      continue;
    }
    if (!/\.(ts|tsx)$/.test(f)) continue;
    const t = fs.readFileSync(f, "utf8");
    for (const m of t.matchAll(/export\s+(?:declare\s+)?(?:default\s+)?(?:async\s+)?(?:abstract\s+)?(?:function\*?|const|let|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/g)) names.add(m[1]);
    for (const m of t.matchAll(/export\s+(?:type\s+)?\{([^}]*)\}/g)) {
      for (const part of m[1].split(",")) {
        const name = part.trim().split(/\s+as\s+/).pop()?.replace(/^type\s+/, "").trim();
        if (name) names.add(name);
      }
    }
  }
  return names;
}

/** Names the Swift package declares publicly. */
function swiftNames() {
  const names = new Set();
  for (const f of walk(path.join(root, "packages/swift/Sources"))) {
    if (!f.endsWith(".swift")) continue;
    const t = fs.readFileSync(f, "utf8");
    for (const m of t.matchAll(/public\s+(?:final\s+)?(?:class|struct|enum|protocol|actor|typealias|func|let|var)\s+([A-Za-z_][\w]*)/g)) names.add(m[1]);
  }
  return names;
}

const known = { core: tsNames("core"), react: tsNames("react"), svelte: tsNames("svelte"), swift: swiftNames() };
// The framework packages may name a core API ("Via core", `createX` from core).
const lookup = (column, name) => known[column].has(name) || (column !== "swift" && known.core.has(name));

/** Components, hooks, factories and types a cell names: `<X>`, `useX`, `createX`, `PascalCase`. */
function apiNames(cell) {
  const out = new Set();
  for (const m of cell.matchAll(/`([^`]+)`/g)) {
    const id = m[1].match(/^<?([A-Za-z_$][\w$]*)/);
    if (id) out.add(id[1]);
  }
  for (const m of cell.matchAll(/<([A-Z]\w*)[\s/>]/g)) out.add(m[1]);
  return [...out].filter((n) => /^(use[A-Z]|create[A-Z]|[A-Z])/.test(n));
}

for (const area of manifest.areas) {
  if (!area.features.length) problems.push(`${area.title} has no features.`);
  for (const f of area.features) {
    for (const [key] of COLUMNS) {
      if (typeof f[key] !== "string" || !f[key].trim()) {
        problems.push(`${area.title} / ${f.feature}: the ${key} cell is empty.`);
        continue;
      }
      if (/(?<!\\)\|/.test(f[key])) problems.push(`${area.title} / ${f.feature}: the ${key} cell has a "|"; write it as "\\|".`);
      for (const name of apiNames(f[key])) {
        if (name in (manifest.notExports ?? {})) continue;
        if (!lookup(key, name)) problems.push(`${area.title} / ${f.feature}: ${key} names \`${name}\`, which ${key === "swift" ? "packages/swift" : `packages/${key}`} does not export.`);
      }
    }
  }
}

// MARK: write or check

let stale = 0;
for (const [file, text, current] of [
  [readmePath, nextReadme, readme],
  [demoPath, demo, fs.existsSync(demoPath) ? fs.readFileSync(demoPath, "utf8") : null],
]) {
  if (text === current) continue;
  stale++;
  if (check) problems.push(`${path.relative(root, file)} is out of date: run node scripts/parity.mjs.`);
  else fs.writeFileSync(file, text);
}
if (problems.length) {
  for (const p of problems) console.error(p);
  console.error(`${problems.length} problem(s) in the feature matrix.`);
  process.exit(1);
}
console.log(check ? "parity: up to date" : `parity: ${stale} file(s) written`);
