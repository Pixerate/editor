/** Looks up a built-in id (case-insensitive; a few aliases and the descriptions too). */
export function builtinProfileId(s: string): BuiltinProfileId | null {
  const n = s.toLowerCase().replace(/[^a-z0-9]/g, '');
  const aliases: Record<string, BuiltinProfileId> = {
    srgb: 'srgb',
    srgbiec6196621: 'srgb',
    p3: 'display-p3',
    displayp3: 'display-p3',
    adobergb: 'adobe-rgb-compat',
    adobergb1998: 'adobe-rgb-compat',
    adobergbcompat: 'adobe-rgb-compat',
    prophoto: 'prophoto-compat',
    prophotorgb: 'prophoto-compat',
    prophotocompat: 'prophoto-compat',
    linearsrgb: 'linear-srgb',
    rec2020: 'rec2020',
    bt2020: 'rec2020',
    gray: 'gray-gamma-2.2',
    graygamma22: 'gray-gamma-2.2',
    sgray: 'sgray',
    dotgain20: 'dot-gain-20-compat',
    dotgain20compat: 'dot-gain-20-compat',
    lab: 'lab-d50',
    labd50: 'lab-d50',
    cmyk: 'coated-cmyk',
    coatedcmyk: 'coated-cmyk',
  };
  return aliases[n] ?? BUILTIN_PROFILES.find((b) => b.description.toLowerCase() === s.toLowerCase())?.id ?? null;
}

/** Colorants adapted to D50 and quantised, each row nudged so RGB (1, 1, 1) is exactly the stored D50 white. */
function colorants(r: number[], g: number[], b: number[], white: number[]): { m: Mat3; chad: Mat3 | null } {
  const m = rgbToXyzMatrix(r, g, b, white)!;
  const d50 = d50Quantized();
  const nearD50 = Math.abs(white[0] - D50[0]) < 1e-3 && Math.abs(white[2] - D50[2]) < 1e-3;
  const adapt = nearD50 ? null : bradford(white, D50);
  let m50: Mat3;
  if (adapt) m50 = mul(adapt, m);
  else {
    const s = apply(m, [1, 1, 1]);
    m50 = m.map((row, i) => row.map((v) => (v * D50[i]) / s[i])) as Mat3;
  }
  const q = m50.map((row) => row.map(s15f16Round)) as Mat3;
  for (let i = 0; i < 3; i++) {
    const row = q[i];
    const err = d50[i] - (row[0] + row[1] + row[2]);
    let k = 0;
    for (let j = 1; j < 3; j++) if (Math.abs(row[j]) > Math.abs(row[k])) k = j;
    row[k] = s15f16Round(row[k] + err);
  }
  return { m: q, chad: adapt ? (adapt.map((row) => row.map(s15f16Round)) as Mat3) : null };
}

const withBytes = (p: Profile): Profile => ({ ...p, bytes: encodeProfile(p) });

function rgbProfile(desc: string, prim: number[][], white: number[], trc: Curve): Profile {
  const { m, chad } = colorants(prim[0], prim[1], prim[2], white);
  return withBytes({
    version: [4, 0x30],
    profileClass: 'display',
    colorSpace: 'rgb',
    pcs: 'xyz',
    renderingIntent: 'perceptual',
    description: desc,
    copyright: BUILTIN_COPYRIGHT,
    whitePoint: d50Quantized(),
    blackPoint: null,
    chad,
    matrix: m,
    trc: [trc, trc, trc],
    grayTrc: null,
    a2b: [null, null, null],
    b2a: [null, null, null],
    bytes: null,
  });
}

function grayProfile(desc: string, trc: Curve): Profile {
  return withBytes({
    version: [4, 0x30],
    profileClass: 'display',
    colorSpace: 'gray',
    pcs: 'xyz',
    renderingIntent: 'perceptual',
    description: desc,
    copyright: BUILTIN_COPYRIGHT,
    whitePoint: d50Quantized(),
    blackPoint: null,
    chad: null,
    matrix: null,
    trc: null,
    grayTrc: trc,
    a2b: [null, null, null],
    b2a: [null, null, null],
    bytes: null,
  });
}

function labProfile(desc: string): Profile {
  const ident = () => ({ kind: 'ab' as const, inputs: 3, outputs: 3, stages: [{ kind: 'curves' as const, curves: [IDENTITY_CURVE, IDENTITY_CURVE, IDENTITY_CURVE] }] });
  return withBytes({
    version: [4, 0x30],
    profileClass: 'colorspace',
    colorSpace: 'lab',
    pcs: 'lab',
    renderingIntent: 'perceptual',
    description: desc,
    copyright: BUILTIN_COPYRIGHT,
    whitePoint: d50Quantized(),
    blackPoint: null,
    chad: null,
    matrix: null,
    trc: null,
    grayTrc: null,
    a2b: [ident(), null, null],
    b2a: [ident(), null, null],
    bytes: null,
  });
}

function build(id: BuiltinProfileId): Profile {
  const desc = BUILTIN_PROFILES.find((b) => b.id === id)!.description;
  const d65 = xyToXyz(D65_XY);
  const srgbP = [
    [0.64, 0.33],
    [0.3, 0.6],
    [0.15, 0.06],
  ];
  switch (id) {
    case 'srgb':
      return rgbProfile(desc, srgbP, d65, srgbTrc());
    case 'display-p3':
      return rgbProfile(desc, [[0.68, 0.32], [0.265, 0.69], [0.15, 0.06]], d65, srgbTrc());
    case 'adobe-rgb-compat':
      return rgbProfile(desc, [[0.64, 0.33], [0.21, 0.71], [0.15, 0.06]], d65, gammaCurve(563 / 256));
    case 'prophoto-compat':
      return rgbProfile(desc, [[0.7347, 0.2653], [0.1596, 0.8404], [0.0366, 0.0001]], [D50[0], D50[1], D50[2]], gammaCurve(1.8));
    case 'linear-srgb':
      return rgbProfile(desc, srgbP, d65, gammaCurve(1));
    case 'rec2020': {
      // The inverse Rec. 709 OETF: V = 1.099 L^0.45 − 0.099 (L ≥ 0.018), 4.5 L below.
      const a = 1.099;
      return rgbProfile(desc, [[0.708, 0.292], [0.17, 0.797], [0.131, 0.046]], d65, { type: 'parametric', kind: 3, p: [1 / 0.45, 1 / a, (a - 1) / a, 1 / 4.5, 0.081, 0, 0] });
    }
    case 'gray-gamma-2.2':
      return grayProfile(desc, gammaCurve(2.2));
    case 'sgray':
      return grayProfile(desc, srgbTrc());
    case 'dot-gain-20-compat':
      return grayProfile(desc, gammaCurve(1.732));
    case 'lab-d50':
      return labProfile(desc);
    case 'coated-cmyk': {
      const p = cmykProfile(undefined, BUILTIN_COPYRIGHT);
      const bytes = encodeProfile(p);
      // Read back from its own bytes, so it evaluates exactly as an embedded copy would.
      return { ...parseProfile(bytes), bytes };
    }
  }
}

const built = new Map<BuiltinProfileId, Profile>();

/** A built-in profile (built once; the synthetic CMYK takes about a second the first time). */
export function builtinProfile(id: BuiltinProfileId): Profile {
  let p = built.get(id);
  if (!p) {
    p = build(id);
    built.set(id, p);
  }
  return p;
}

/** sRGB IEC 61966-2.1, the default working space. */
export const srgbProfile = () => builtinProfile('srgb');

/** The default profile of a colour space: sRGB, Dot Gain 20 %-compatible grey, the coated CMYK, Lab D50. */
export function defaultProfileFor(cs: ColorSpace): Profile | null {
  switch (cs) {
    case 'rgb':
      return builtinProfile('srgb');
    case 'gray':
      return builtinProfile('dot-gain-20-compat');
    case 'cmyk':
      return builtinProfile('coated-cmyk');
    case 'lab':
      return builtinProfile('lab-d50');
    default:
      return null;
  }
}
