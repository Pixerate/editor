export interface VectorCommandOptions {
	/** Id prefix (default `vector.`); use one per editor when several are registered. */
	prefix?: string;
	/** Palette group (default `Vector`). */
	group?: string;
	/** Command scope. Omit for global commands. */
	scope?: string;
}

/** A node as listed for agents. */
export interface VectorNodeListing {
	id: string;
	type: 'path' | 'group';
	name?: string;
	depth: number;
	/** Axis-aligned bounds in document units. */
	bounds: { x: number; y: number; width: number; height: number } | null;
	/** Rotation in degrees, clockwise (ancestors' rotations included). */
	rotation: number;
	visible: boolean;
	locked: boolean;
	selected: boolean;
	fill?: unknown;
	stroke?: unknown;
	strokeWidth?: number;
	/** SVG path data (paths only). */
	d?: string;
	children?: number;
	/** A blend group's options (its steps are listed as children with `blendStep`). */
	blend?: { spacing: string; steps: number; distance: number; orientToSpine: boolean; linear: boolean; spine: boolean; keys: string[] };
	/** An in-between generated by a blend (locked; changes come from its keys). */
	blendStep?: boolean;
	/** The node's live path effects, applied in order. */
	effects?: VectorEffect[];
	/** A live boolean group's operation (its children are the operands). */
	liveBoolean?: VectorBooleanOperation;
	/** An operand's own operation in a live boolean group. */
	booleanOperation?: VectorBooleanOperation;
	/** The fill stack, bottom to top, when the path has more than its `fill` says. */
	fills?: VectorPaintLayer[];
	/** The stroke stack, bottom to top, when the path has more than its `stroke` says. */
	strokes?: VectorStrokeLayer[];
	/** The node's blend mode, when not normal. */
	blendMode?: VectorBlendMode;
	/** The node's visual filters (shadows, glows, blurs, feather). */
	filters?: VectorFilter[];
	/** A mask group's mask: type, inversion, the mask's id (its first child) and the masked contents. */
	mask?: VectorMaskSummary;
}

