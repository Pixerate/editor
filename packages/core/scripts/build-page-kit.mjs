#!/usr/bin/env node
/**
 * Builds the page kit (#814): bundles `src/page-kit/kit.ts` into one minified IIFE and writes
 * `src/page-kit/bundle.generated.ts` with it and the guide as strings, so
 * `@pixerate/editor/page-kit` imports nothing. Deterministic: the same sources give the same
 * file. `--check` fails when the committed file is stale (tests run the same check).
 *
 *   node scripts/build-page-kit.mjs [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const require = createRequire(import.meta.url);
// esbuild comes with tsup (the package's bundler); resolve it from there.
const esbuild = require(require.resolve('esbuild', { paths: [require.resolve('tsup')] }));

/** The page kit as `{ bundle, guide, version, hash, source }`. */
export async function buildPageKit() {
	const result = await esbuild.build({
		entryPoints: [join(root, 'src/page-kit/kit.ts')],
		bundle: true,
		write: false,
		format: 'iife',
		platform: 'browser',
		target: 'es2019',
		minify: true,
		legalComments: 'none',
		charset: 'utf8',
		treeShaking: true,
		logLevel: 'silent'
	});
	const bundle = result.outputFiles[0].text.trim();
	const guide = readFileSync(join(root, 'src/page-kit/guide.md'), 'utf8');
	const version = /export const KIT_VERSION = '([^']+)'/.exec(readFileSync(join(root, 'src/page-kit/kit.ts'), 'utf8'))[1];
	const hash = createHash('sha256').update(bundle).digest('hex').slice(0, 16);
	const source = [
		'// Generated by scripts/build-page-kit.mjs from src/page-kit/kit.ts and guide.md. Do not edit.',
		'',
		`/** The page kit's version (\`pixerateKit.version\`). */`,
		`export const PAGE_KIT_VERSION: string = ${JSON.stringify(version)};`,
		'',
		'/** First 16 hex digits of the bundle\'s SHA-256, to tell builds apart. */',
		`export const PAGE_KIT_HASH: string = ${JSON.stringify(hash)};`,
		'',
		'/** The kit: a minified script that sets `window.pixerateKit`. Inline it in a page. */',
		`export const PAGE_KIT: string = ${JSON.stringify(bundle)};`,
		'',
		'/** The guide for models: what the kit holds and when to use each helper (Markdown). */',
		`export const PAGE_KIT_GUIDE: string = ${JSON.stringify(guide)};`,
		''
	].join('\n');
	return { bundle, guide, version, hash, source };
}

const OUT = join(root, 'src/page-kit/bundle.generated.ts');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const { source, bundle } = await buildPageKit();
	if (process.argv.includes('--check')) {
		const committed = readFileSync(OUT, 'utf8');
		if (committed !== source) {
			console.error('page-kit: src/page-kit/bundle.generated.ts is stale; run node scripts/build-page-kit.mjs');
			process.exit(1);
		}
		console.log('page-kit: up to date');
	} else {
		writeFileSync(OUT, source);
		console.log(`page-kit: wrote ${Buffer.byteLength(bundle)} bytes`);
	}
}
